"""Generate `docs/api-reference.md` from the code, so it cannot drift.

    python -m scripts.api_docs            # rewrite the file
    python -m scripts.api_docs --check    # exit 1 if the file is out of date

Contents: every endpoint with the permission it needs, the role-permission matrix
and the ticket state diagram. A test runs the `--check` logic.
"""

import sys
from pathlib import Path

from fastapi.routing import APIRoute

from app.api.dependencies import AuthenticatedOnly, RequirePermission
from app.core.authz import ADMIN, AUDITOR, EMPLOYEE, SUPERVISOR, TECHNICIAN
from app.core.permissions import CATALOG, effective_for_system_roles
from app.domain.ticket_state import TicketState
from app.main import API_ROUTERS

OUTPUT = Path(__file__).resolve().parents[2] / "docs" / "api-reference.md"
ROLES = (ADMIN, SUPERVISOR, TECHNICIAN, EMPLOYEE, AUDITOR)
STATE_ORDER = (
    "submitted",
    "triaged",
    "assigned",
    "in_progress",
    "waiting",
    "resolved",
    "closed",
    "cancelled",
)


def _access(route: APIRoute) -> str:
    stack = [route.dependant]
    authenticated = False
    while stack:
        node = stack.pop()
        call = node.call
        if isinstance(call, RequirePermission):
            return f"`{call.code}`"
        if isinstance(call, AuthenticatedOnly):
            authenticated = True
        stack.extend(node.dependencies)
    return "any signed-in user" if authenticated else "public"


def _endpoint_rows() -> list[tuple[str, str, str, str]]:
    rows = []
    for router in API_ROUTERS:
        for route in router.routes:
            if not isinstance(route, APIRoute):
                continue
            summary = route.summary or route.name.replace("_", " ").capitalize()
            for method in sorted(route.methods - {"HEAD", "OPTIONS"}):
                rows.append((route.path, method, summary, _access(route)))
    rows.append(("/health", "GET", "Liveness check", "public"))
    return sorted(rows, key=lambda r: (r[0], r[1]))


def _tags_by_path() -> dict[str, str]:
    tags: dict[str, str] = {}
    for router in API_ROUTERS:
        for route in router.routes:
            if isinstance(route, APIRoute) and route.tags:
                tags[route.path] = str(route.tags[0])
    return tags


def build_markdown() -> str:
    lines = [
        "# API reference",
        "",
        "> Generated by `python -m scripts.api_docs` from the code. Do not edit by hand.",
        (
            "> Interactive docs (non-production): `/docs`. Authentication is delegated to "
            "Clerk (`Authorization: Bearer <session JWT>`); see the README."
        ),
        "",
        "## Endpoints",
        "",
    ]
    tags = _tags_by_path()
    rows = _endpoint_rows()
    for tag in sorted({tags.get(path, "system") for path, *_ in rows}):
        lines += [
            f"### {tag}",
            "",
            "| Method | Path | Summary | Access |",
            "| --- | --- | --- | --- |",
        ]
        for path, method, summary, access in rows:
            if tags.get(path, "system") == tag:
                lines.append(f"| {method} | `{path}` | {summary} | {access} |")
        lines.append("")
    lines += [
        f"Total: **{len(rows)}** endpoints.",
        "",
        (
            "Listings accept `page`, `size`, `sort` (`field` / `-field`) and `search` and report "
            "the page in the `X-Total-Count`, `X-Page`, `X-Page-Size` and `X-Total-Pages` headers. "
            "Errors always use `{detail, code, errors, request_id}`."
        ),
        "",
        "## Role-permission matrix",
        "",
        "| Permission | " + " | ".join(ROLES) + " |",
        "| --- | " + " | ".join("---" for _ in ROLES) + " |",
    ]
    effective = {role: effective_for_system_roles(role) for role in ROLES}
    for permission in CATALOG:
        marks = ["yes" if permission in effective[role] else "-" for role in ROLES]
        lines.append(f"| `{permission}` | " + " | ".join(marks) + " |")
    lines += [
        "",
        (
            "Roles inherit: EMPLOYEE → TECHNICIAN → SUPERVISOR → ADMIN (AUDITOR stands alone). "
            "Data scope follows `ver` (own), `ver_asignados` (assigned to the person) and "
            "`ver_todos` (everything)."
        ),
        "",
        "## Ticket state diagram",
        "",
        "```mermaid",
        "stateDiagram-v2",
        "    [*] --> submitted",
    ]
    for status in STATE_ORDER:
        state = TicketState.of(status)
        for target in STATE_ORDER:
            if target in state.allowed_targets:
                note = (
                    " : needs technician"
                    if TicketState.of(target).requires_technician
                    else ""
                )
                lines.append(f"    {status} --> {target}{note}")
        if state.is_terminal:
            lines.append(f"    {status} --> [*]")
    lines += [
        "```",
        "",
        "| State | Can move to | On entry | Notifies requester |",
        "| --- | --- | --- | --- |",
    ]
    effects = {
        "assigned": "requires an active technician assignment",
        "resolved": "sets `resolved_at` and the resolution summary",
        "closed": "sets `closed_at`",
    }
    for status in STATE_ORDER:
        state = TicketState.of(status)
        targets = (
            ", ".join(f"`{t}`" for t in STATE_ORDER if t in state.allowed_targets)
            or "- (terminal)"
        )
        lines.append(
            f"| `{status}` | {targets} | {effects.get(status, '-')} | "
            f"{'yes' if state.notifies_requester else 'no'} |"
        )
    lines += [
        "",
        (
            "Assigning a technician moves `submitted`/`triaged` tickets to `assigned` through the "
            "same guarded transition; reassigning later keeps the current state."
        ),
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    content = build_markdown()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current.replace("\r\n", "\n") != content:
            print(
                "docs/api-reference.md is out of date: run `python -m scripts.api_docs`"
            )
            return 1
        return 0
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
