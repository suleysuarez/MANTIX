"""File storage port and its local-disk implementation.

Services depend on the `FileStorage` protocol, so the disk can later be swapped
for an object store (S3, R2, ...) without touching business code. Storage keys
are generated by the server; client-supplied names never reach the filesystem.
"""

import asyncio
from pathlib import Path
from typing import Protocol

from app.core.exceptions import NotFoundError


class FileStorage(Protocol):
    async def save(self, key: str, content: bytes) -> None: ...

    async def read(self, key: str) -> bytes: ...

    async def delete(self, key: str) -> None: ...


class LocalFileStorage:
    """Stores files under `base_dir`; refuses keys that would escape it."""

    def __init__(self, base_dir: str | Path):
        self.base_dir = Path(base_dir).resolve()

    def _path(self, key: str) -> Path:
        path = (self.base_dir / key).resolve()
        if not path.is_relative_to(self.base_dir) or path == self.base_dir:
            raise ValueError("invalid storage key")
        return path

    async def save(self, key: str, content: bytes) -> None:
        path = self._path(key)

        def write() -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)

        await asyncio.to_thread(write)

    async def read(self, key: str) -> bytes:
        path = self._path(key)
        try:
            return await asyncio.to_thread(path.read_bytes)
        except FileNotFoundError:
            raise NotFoundError("the stored file is missing") from None

    async def delete(self, key: str) -> None:
        path = self._path(key)
        await asyncio.to_thread(path.unlink, True)  # missing_ok
